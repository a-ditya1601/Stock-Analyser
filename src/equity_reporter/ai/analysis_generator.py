DETERMINISTIC_STATUS_LABEL = "Deterministic v2 (Local, No External AI Call)"
DETERMINISTIC_STATUS_NOTE = "Enhanced local rule-based narrative generated without external API."


@dataclass(slots=True, frozen=True)
class AIAnalysisResult:
    text: str
    used_ai: bool
    status_label: str
    status_note: str


def generate_comprehensive_analysis(
    snapshot: MarketSnapshot,
    signals: dict[str, Any],
    projections: ProjectionScenarios,
    scorecard: ScoreCard,
    *,
    nvidia_service: NvidiaService | None = None,
    enable_ai: bool | None = None,
) -> AIAnalysisResult:
    logger = get_logger(__name__)
    fallback_text = _build_deterministic_v2_text(scorecard, signals, projections)
    ai_enabled = is_nvidia_narrative_enabled() if enable_ai is None else enable_ai

    if not ai_enabled:
        return AIAnalysisResult(
            text=fallback_text,
            used_ai=False,
            status_label=DETERMINISTIC_STATUS_LABEL,
            status_note=DETERMINISTIC_STATUS_NOTE,
        )

    try:
        composed = build_structured_prompt_input(snapshot, signals, projections, scorecard)
        service = nvidia_service or NvidiaService()
        generated = service.generate_text(
            system_prompt=composed.system_prompt,
            user_prompt=composed.user_prompt,
        )
        normalized = _normalize_generated_text(generated)
        if normalized == DATA_UNAVAILABLE:
            return AIAnalysisResult(
                text=fallback_text,
                used_ai=False,
                status_label="Deterministic v2 (AI Fallback)",
                status_note="AI response was empty or malformed, so deterministic narrative was used.",
            )

        return AIAnalysisResult(
            text=normalized,
            used_ai=True,
            status_label="Nvidia Applied",
            status_note="AI narrative generated by Nvidia from structured in-run data payload.",
        )
    except NvidiaServiceError as exc:
        logger.warning("nvidia.narrative.fallback category=%s", type(exc).__name__)
        return AIAnalysisResult(
            text=fallback_text,
            used_ai=False,
            status_label="Deterministic v2 (AI Fallback)",
            status_note="AI service was unavailable in this run, so deterministic narrative was used.",
        )
    except Exception:
        logger.exception("nvidia.narrative.unexpected_fallback")
        return AIAnalysisResult(
            text=fallback_text,
            used_ai=False,
            status_label="Deterministic v2 (AI Fallback)",
            status_note="Unexpected AI runtime issue occurred; deterministic narrative was used.",
        )


def _normalize_generated_text(text: str | None) -> str:
    if text is None:
        return DATA_UNAVAILABLE

    lines = [line.rstrip() for line in text.splitlines()]
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()

    cleaned = "\n".join(lines).strip()
    return cleaned if cleaned else DATA_UNAVAILABLE


def _build_deterministic_v2_text(
    scorecard: ScoreCard,
    signals: dict[str, Any],
    projections: ProjectionScenarios,
) -> str:
    narratives = build_narratives(scorecard, signals)
    fundamental_signals = _as_signal_map(signals.get("fundamental_signals"))
    technical_signals = _as_signal_map(signals.get("technical_signals"))
    volume_signals = _as_signal_map(signals.get("volume_signals"))
    fib_signal = signals.get("fibonacci_signal") if isinstance(signals.get("fibonacci_signal"), MetricSignal) else None

    strongest_upside = _top_metric_signal(scorecard, labels=(SignalLabel.BULLISH,))
    strongest_risk = _top_metric_signal(scorecard, labels=(SignalLabel.BEARISH, SignalLabel.WARNING))

    executive = (
        f"Model verdict is {scorecard.verdict} with confidence {scorecard.final_score:.2f}% "
        f"and data coverage {scorecard.data_coverage_pct:.2f}%. "
        f"{narratives.overall_note or DATA_UNAVAILABLE}\n"
        f"Category posture: Fundamental {_fmt_percent(scorecard.category_scores.get('fundamental'))}, "
        f"Technical {_fmt_percent(scorecard.category_scores.get('technical'))}, "
        f"Volume/Risk/F&O {_fmt_percent(scorecard.category_scores.get('volume_risk'))}, "
        f"Peer Relativity {_fmt_percent(scorecard.category_scores.get('peer_relativity'))}.\n"
        f"Biggest upside catalyst: {_signal_takeaway(strongest_upside, narratives.metric_notes)}\n"
        f"Biggest risk factor: {_signal_takeaway(strongest_risk, narratives.metric_notes)}"
    )

    missing_fundamentals = _missing_metric_labels(
        scorecard,
        (
            "valuation_pe_trend",
            "quarterly_revenue_growth",
            "profit_margin",
            "operating_margin",
            "return_on_equity",
            "return_on_capital_employed",
            "debt_to_equity",
            "current_ratio",
            "fcf_vs_debt",
        ),
    )
    fundamentals = (
        f"{narratives.category_notes.get('fundamental', DATA_UNAVAILABLE)}\n"
        f"Valuation vs growth: {_metric_note(narratives, 'valuation_pe_trend')} "
        f"{_metric_note(narratives, 'quarterly_revenue_growth')} {_metric_note(narratives, 'profit_margin')} "
        f"{_metric_note(narratives, 'operating_margin')}\n"
        f"Capital efficiency: {_metric_note(narratives, 'return_on_equity')} "
        f"{_metric_note(narratives, 'return_on_capital_employed')}\n"
        f"Balance sheet and durability: {_metric_note(narratives, 'debt_to_equity')} "
        f"{_metric_note(narratives, 'current_ratio')} {_metric_note(narratives, 'fcf_vs_debt')}\n"
        f"Critical missing fundamental metrics: {missing_fundamentals}"
    )

    technical_volume = (
        f"{narratives.category_notes.get('technical', DATA_UNAVAILABLE)}\n"
        f"Trend framework: {_metric_note(narratives, 'sma_crossover')} {_metric_note(narratives, 'ichimoku_cloud')} "
        f"{_metric_note(narratives, 'fibonacci_support_breakout')}\n"
        f"Momentum stack: {_metric_note(narratives, 'rsi_14')} {_metric_note(narratives, 'macd_crossover')} "
        f"{_metric_note(narratives, 'bollinger_position')} {_metric_note(narratives, 'adx_trend_strength')}\n"
        f"Order flow and participation: {narratives.category_notes.get('volume_risk', DATA_UNAVAILABLE)} "
        f"{_metric_note(narratives, 'obv_30d_trend')} {_metric_note(narratives, 'relative_volume_10d_3m')}\n"
        f"Derivatives smart-money context: {_safe_text(signals.get('fno_text_block'))}"
    )

    volatility_risk = (
        f"Beta profile (weekly/1M/1Y/2Y/5Y): "
        f"{_fmt_number(signals.get('beta_weekly'))} / {_fmt_number(signals.get('beta_1m'))} / "
        f"{_fmt_number(signals.get('beta'))} / {_fmt_number(signals.get('beta_2y'))} / {_fmt_number(signals.get('beta_5y'))}. "
        f"Benchmark: {_safe_text(signals.get('beta_benchmark'))}.\n"
        f"F&O risk overlay: PCR {_fmt_number(signals.get('fno_pcr'))}, rollover "
        f"{_fmt_percent(signals.get('fno_rollover_pct'))}, ATM IV {_fmt_percent(signals.get('fno_atm_iv'))}, "
        f"max pain {_fmt_number(signals.get('fno_max_pain'))}.\n"
        f"Trend-state risk overlay: {_metric_note_from_signal(technical_signals.get('adx_trend_strength'))} "
        f"{_metric_note_from_signal(fundamental_signals.get('beta_profile_fit'))}"
    )

    tactical_execution = _build_tactical_execution_text(signals, projections, fib_signal)
    manual_trade_management = _build_manual_trade_management_text(signals, projections)
    scenarios = _build_scenario_text(projections)
    macro_stress = _build_macro_stress_text(signals, narratives)
    sector_relativity = _build_sector_relativity_text(signals, narratives)

    return (
        "## 1. Fundamental Deep-Dive & Valuation\n"
        f"{fundamentals}\n\n"
        "## 2. Technical Posture & Volume Accumulation\n"
        f"{technical_volume}\n\n"
        "## 3. Volatility & Risk Matrix\n"
        f"{volatility_risk}\n\n"
        "## 4. Tactical Execution Plan\n"
        f"{tactical_execution}\n\n"
        "## 5. Manual Trade Management & Invalidation Rules\n"
        f"{manual_trade_management}\n\n"
        "## 6. Scenario Modeling & Price Action Matrix\n"
        f"{scenarios}\n\n"
        "## 7. Macro Stress Test\n"
        f"{macro_stress}\n\n"
        "## 8. Sector Relativity (Conditional)\n"
        f"{sector_relativity}\n\n"
        "## 9. Executive Summary & Verdict\n"
        f"{executive}"
    )


def _build_tactical_execution_text(
    signals: dict[str, Any],
    projections: ProjectionScenarios,
    fib_signal: MetricSignal | None,
) -> str:
    latest = _fmt_number(signals.get("latest_close"))
    sma_50 = _fmt_number(signals.get("sma_50"))
    sma_200 = _fmt_number(signals.get("sma_200"))
    fib_382 = _fmt_number(signals.get("fib_0_382"))
    fib_500 = _fmt_number(signals.get("fib_0_500"))
    fib_618 = _fmt_number(signals.get("fib_0_618"))
    fib_note = _metric_note_from_signal(fib_signal)

    projection_2m = _horizon_projection_line(projections, "1-2 months")
    projection_4m = _horizon_projection_line(projections, "3-4 months")
    projection_6m = _horizon_projection_line(projections, "5-6 months")

    return (
        f"Reference price: {latest}. Tactical anchors: SMA50 {sma_50}, SMA200 {sma_200}, "
        f"Fib levels 0.382 {fib_382}, 0.500 {fib_500}, 0.618 {fib_618}. {fib_note}\n"
        f"Projection grid (bear/base/bull): {projection_2m}; {projection_4m}; {projection_6m}.\n"
        "Execution guidance: favor entries near validated support with predefined stop-loss below key support; "
        "reduce size when volatility expands without confirmation."
    )


def _build_manual_trade_management_text(
    signals: dict[str, Any],
    projections: ProjectionScenarios,
) -> str:
    sma_20 = _to_float(signals.get("sma_20"))
    sma_50 = _to_float(signals.get("sma_50"))
    sma_200 = _to_float(signals.get("sma_200"))
    fib_618 = _to_float(signals.get("fib_0_618"))
    relative_volume = _to_float(signals.get("relative_volume_10d_3m"))
    obv_slope = _to_float(signals.get("obv_30d_slope"))
    macd_value = _to_float(signals.get("macd"))
    macd_signal = _to_float(signals.get("macd_signal"))
    adx_14 = _to_float(signals.get("adx_14"))

    invalidation_rules: list[str] = []
    if sma_50 is not None:
        invalidation_rules.append(
            f"Daily close below SMA50 ({sma_50:.2f}) with expanding participation"
            f"{f' (relative volume > {relative_volume:.2f})' if relative_volume is not None else ''} "
            "invalidates the primary long thesis and requires immediate manual exit."
        )
    if fib_618 is not None:
        invalidation_rules.append(
            f"Weekly close below Fibonacci 61.8% ({fib_618:.2f}) invalidates structural support and mandates bailout."
        )
    if not invalidation_rules and sma_200 is not None:
        invalidation_rules.append(
            f"Two consecutive closes below SMA200 ({sma_200:.2f}) trigger thesis invalidation and full manual de-risking."
        )

    base_target = projections.horizons.get("3-4 months")
    if base_target is None:
        base_target = projections.horizons.get("1-2 months")
    base_value = base_target.base if base_target is not None else None
    trail_anchor = _fmt_number(sma_20)
    if trail_anchor == DATA_UNAVAILABLE:
        trail_anchor = _fmt_number(sma_50)
    profit_schedule = (
        f"Scale out 50% near the base-case objective ({_fmt_number(base_value)}) across the 2-6 month horizon; "
        f"trail the remaining 50% using {'SMA20' if _to_float(signals.get('sma_20')) is not None else 'SMA50'} ({trail_anchor}) "
        "with a closing-basis stop."
    )

    checklist: list[str] = []
    if obv_slope is not None:
        direction = "accumulation" if obv_slope > 0 else "distribution"
        checklist.append(f"OBV trend shift: monitor 30-day OBV slope for deterioration from {direction}.")
    if macd_value is not None and macd_signal is not None:
        checklist.append("MACD contraction risk: track MACD line convergence toward/below signal as early exhaustion.")
    if adx_14 is not None:
        checklist.append(f"Trend-strength decay: ADX(14) rolling below 20 from {adx_14:.2f} signals trend fatigue.")
    if relative_volume is not None:
        checklist.append(
            f"Participation quality: sustained 10D/3M relative volume drift below {max(0.6, relative_volume * 0.7):.2f} is a warning."
        )

    if not invalidation_rules and not checklist and base_value is None and sma_20 is None and sma_50 is None:
        return DATA_UNAVAILABLE

    rules_text = " ".join(invalidation_rules[:2]) if invalidation_rules else DATA_UNAVAILABLE
    checklist_text = " ".join(checklist[:2]) if checklist else DATA_UNAVAILABLE

    return (
        f"Thesis Invalidation: {rules_text}\n"
        f"Profit-Taking Schedule: {profit_schedule}\n"
        f"Active Monitoring Checklist: {checklist_text}"
    )


def _build_scenario_text(projections: ProjectionScenarios) -> str:
    if not projections.horizons:
        return DATA_UNAVAILABLE

    lines: list[str] = []
    for horizon in ("1-2 months", "3-4 months", "5-6 months"):
        line = _horizon_projection_line(projections, horizon)
        if line != DATA_UNAVAILABLE:
            lines.append(line)
    if not lines:
        return DATA_UNAVAILABLE
    return " | ".join(lines)


def _build_macro_stress_text(signals: dict[str, Any], narratives) -> str:  # noqa: ANN001
    beta_weekly = _fmt_number(signals.get("beta_weekly"))
    beta_1y = _fmt_number(signals.get("beta"))
    trailing_pe = _fmt_number(signals.get("trailing_pe"))
    debt_to_equity = _fmt_number(signals.get("debt_to_equity"))
    margin = _fmt_percent(signals.get("profit_margin"), already_percent=False)
    peer_fpe = _fmt_percent(signals.get("peer_forward_pe_premium_pct"))
    peer_pe_ratio = _fmt_number(signals.get("peer_pe_to_sector_pe_ratio"))
    peer_ps = _fmt_percent(signals.get("peer_ps_premium_pct"))
    peer_margin = _fmt_percent(signals.get("peer_margin_spread_pct"))
    peer_growth = _fmt_percent(signals.get("peer_growth_spread_pct"))
    peer_summary = _peer_relativity_summary(signals, narratives)
    return (
        f"Stress lens under a benchmark correction: weekly beta {beta_weekly} vs 1Y beta {beta_1y}, "
        f"trailing P/E {trailing_pe}, debt-to-equity {debt_to_equity}, profit margin {margin}. "
        "Higher beta dispersion with elevated leverage implies faster downside transmission; "
        "margin resilience and cash-flow support reduce fragility when available. "
        f"Peer-relative spreads: forward P/E premium {peer_fpe}, P/S premium {peer_ps}, "
        f"PE-to-sector-PE ratio {peer_pe_ratio}, margin spread {peer_margin}, growth spread {peer_growth}. {peer_summary}"
    )


def _build_sector_relativity_text(signals: dict[str, Any], narratives) -> str:  # noqa: ANN001
    peer_text = _safe_text(signals.get("peer_sector_text"))
    peer_summary = _peer_relativity_summary(signals, narratives)
    if peer_text == DATA_UNAVAILABLE:
        return (
            f"{peer_summary} Sector peer comparison text is {DATA_UNAVAILABLE}, so this run remains "
            "primarily absolute-metric driven."
        )
    return f"{peer_summary} Context block: {peer_text}"


def _as_signal_map(value: Any) -> dict[str, MetricSignal]:
    if not isinstance(value, dict):
        return {}
    output: dict[str, MetricSignal] = {}
    for key, item in value.items():
        if isinstance(item, MetricSignal):
            output[str(key)] = item
    return output


def _top_metric_signal(scorecard: ScoreCard, labels: tuple[SignalLabel, ...]) -> MetricSignal | None:
    candidates: list[MetricSignal] = []
    for metric_signal in scorecard.metric_signals.values():
        if metric_signal.label not in labels:
            continue
        if not metric_signal.available:
            continue
        candidates.append(metric_signal)
    if not candidates:
        return None
    return max(candidates, key=lambda signal: signal.weight * signal.score)


def _signal_takeaway(signal: MetricSignal | None, metric_notes: dict[str, str]) -> str:
    if signal is None:
        return DATA_UNAVAILABLE
    return metric_notes.get(signal.key) or signal.note or DATA_UNAVAILABLE


def _metric_note(narratives, metric_key: str) -> str:  # noqa: ANN001
    return narratives.metric_notes.get(metric_key, DATA_UNAVAILABLE)


def _metric_note_from_signal(signal: MetricSignal | None) -> str:
    if signal is None:
        return DATA_UNAVAILABLE
    if not signal.available:
        return DATA_UNAVAILABLE
    return signal.note or DATA_UNAVAILABLE


def _horizon_projection_line(projections: ProjectionScenarios, horizon: str) -> str:
    rng = projections.horizons.get(horizon)
    if rng is None:
        return DATA_UNAVAILABLE
    return (
        f"{horizon}: bear {_fmt_number(rng.bear)}, base {_fmt_number(rng.base)}, bull {_fmt_number(rng.bull)}"
    )


def _missing_metric_labels(scorecard: ScoreCard, metric_keys: tuple[str, ...]) -> str:
    missing: list[str] = []
    for metric_key in metric_keys:
        signal = scorecard.metric_signals.get(metric_key)
        if signal is None or not signal.available:
            missing.append(metric_key.replace("_", " ").title())
    if not missing:
        return "None"
    return ", ".join(missing)


def _fmt_number(value: Any) -> str:
    numeric = _to_float(value)
    if numeric is None:
        return DATA_UNAVAILABLE
    return f"{numeric:.2f}"


def _fmt_percent(value: Any, *, already_percent: bool = True) -> str:
    numeric = _to_float(value)
    if numeric is None:
        return DATA_UNAVAILABLE
    if already_percent:
        if abs(numeric) <= 1.0:
            numeric = numeric * 100.0
    else:
        numeric = numeric * 100.0
    return f"{numeric:.2f}%"


def _safe_text(value: Any) -> str:
    text = str(value or "").strip()
    return text if text else DATA_UNAVAILABLE


def _peer_relativity_summary(signals: dict[str, Any], narratives) -> str:  # noqa: ANN001
    peer_signals = _as_signal_map(signals.get("peer_signals"))
    if not peer_signals:
        return "Sector peer data is unavailable, so relative positioning remains inconclusive."

    bullish = sum(1 for signal in peer_signals.values() if signal.available and signal.label == SignalLabel.BULLISH)
    bearish = sum(1 for signal in peer_signals.values() if signal.available and signal.label == SignalLabel.BEARISH)
    warning = sum(1 for signal in peer_signals.values() if signal.available and signal.label == SignalLabel.WARNING)

    if bullish >= 2 and bearish == 0:
        stance = "Relative posture suggests sector leadership."
    elif bearish >= 2:
        stance = "Relative posture suggests laggard behavior versus peers."
    elif warning >= 2:
        stance = "Relative posture is mixed with valuation-risk pressure."
    else:
        stance = "Relative posture is close to sector parity with mixed leadership signals."

    category_note = narratives.category_notes.get("peer_relativity", "")
    if category_note:
        return f"{stance} {category_note}"
    return stance


def _to_float(value: Any) -> float | None:
    try:
        if value is None:
            return None
        return float(value)
    except (TypeError, ValueError):
        return None
